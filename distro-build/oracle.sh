# Oracle Linux, from the official container-images rootfs tarballs.
#
# Modelled on termux/proot-distro's distro-build/oracle.sh at commit 5bd8f4f, whose source
# still works: Oracle publishes per-architecture rootfs tarballs in its container-images
# repository and they are fetched by digest branch, so a version is pinnable.
#
# Arch: aarch64 and x86_64. Verified 200 for both.
#
# SELinux is left installed and disabled-by-default, which is what proot needs: proot
# fakes root, not a security context, so an enforcing policy blocks ordinary file
# operations. RedTerm's /root/.startup re-applies that on every start, so nothing has to
# be done to the image beyond excluding the packages that cannot work at all.

dist_name="Oracle Linux"
dist_version="10"
distro_arches="aarch64 x86_64"

# Oracle's branch names in its repository are not its architecture names.
oracle_arch_for() {
	case "$1" in
		aarch64) echo "arm64v8";;
		x86_64) echo "amd64";;
		*) echo "oracle_arch_for(): unknown arch '$1'" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch up_arch rootfs_dir tarball

	for arch in ${distro_arches}; do
		up_arch=$(oracle_arch_for "$arch")
		rootfs_dir="oracle-${arch}"
		tarball="${ROOTFS_DIR}/oracle-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		curl --fail --location \
			--output "${WORKDIR}/oraclelinux-${dist_version}-${up_arch}-rootfs.tar.xz" \
			"https://github.com/oracle/container-images/raw/dist-${up_arch}/${dist_version}/oraclelinux-${dist_version}-${up_arch}-rootfs.tar.xz"

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}"
		sudo mkdir -m 755 "${WORKDIR}/${rootfs_dir}"
		sudo tar -Jxp -f "${WORKDIR}/oraclelinux-${dist_version}-${up_arch}-rootfs.tar.xz" \
			-C "${WORKDIR}/${rootfs_dir}"

		sudo rm -f "${WORKDIR:?}/${rootfs_dir}/etc/resolv.conf"
		sudo tee "${WORKDIR}/${rootfs_dir}/etc/resolv.conf" > /dev/null <<< "nameserver 1.1.1.1"
		sudo find "${WORKDIR}/${rootfs_dir}/dev" -mindepth 1 -delete 2>/dev/null || true

		cat <<- EOF | sudo unshare -mpf bash -e -
			set -e
			echo "excludepkgs=*selinux* filesystem" >> "${WORKDIR}/${rootfs_dir}/etc/dnf/dnf.conf"
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y upgrade
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y install passwd util-linux sudo
			chroot "${WORKDIR}/${rootfs_dir}" dnf clean all
			rm -f "${WORKDIR}/${rootfs_dir}"/var/log/dnf.log
			rm -f "${WORKDIR}/${rootfs_dir}"/var/log/dnf.rpm.log
		EOF

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Oracle Linux"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "dnf -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "oracle" "$arch" "${dist_version}" \
			"\"displayName\": \"Oracle Linux\"" \
			"\"sourceImage\": \"github.com/oracle/container-images dist-${up_arch}/${dist_version}\"" \
			"\"packageManager\": \"dnf\"" \
			"\"recipe\": \"distro-build/oracle.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
		unset up_arch
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/oracle.sh instead.
		DISTRO_NAME="Oracle Linux"
		DISTRO_COMMENT="RHEL-compatible, enterprise. ${dist_version}."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/oracle-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/oracle-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/oracle.sh"
}
