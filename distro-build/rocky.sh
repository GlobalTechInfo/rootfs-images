# Rocky Linux, 10.2.
#
# Modelled on termux/proot-distro's distro-build/rocky.sh at commit 5bd8f4f, which
# calls `docker manifest inspect` and `docker pull`. That is replaced wholesale by
# scripts/oci-unpack.sh: a build host has no Docker daemon and should not need one, and
# three of the four RHEL-family distributions publish only registry images anyway.
#
# Arch: aarch64 and x86_64.
#
# Container images have no machine-id and their SELinux policy is set for a container
# runtime. proot fakes root, not a security context, so SELinux stays installed and disabled-by-default, which is what proot needs.

dist_name="Rocky Linux"
dist_version="10.2"
distro_arches="aarch64 x86_64"

# RedTerm offers this on aarch64 and x86_64 only.
image_ref_for() {
	case "$1" in
		aarch64) echo "docker.io/rockylinux/rockylinux:10";;
		x86_64)  echo "docker.io/rockylinux/rockylinux:10";;
		*) echo "Rocky Linux: no image for $1" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch ref rootfs_dir tarball digest

	for arch in ${distro_arches}; do
		ref=$(image_ref_for "$arch")
		rootfs_dir="rocky-${arch}"
		tarball="${ROOTFS_DIR}/rocky-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" "$ref" "${WORKDIR}/${rootfs_dir}"

		cat <<- EOF | sudo unshare -mpf bash -e -
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y upgrade
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y install passwd util-linux sudo
			chroot "${WORKDIR}/${rootfs_dir}" dnf clean all
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.log"
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.rpm.log"
		EOF

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Rocky Linux"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "dnf -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "rocky" "$arch" "10.2" \
			"\"displayName\": \"Rocky Linux\"" \
			"\"sourceImage\": \"$ref\"" \
			"\"packageManager\": \"dnf\"" \
			"\"recipe\": \"distro-build/rocky.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/rocky.sh instead.
		DISTRO_NAME="Rocky Linux"
		DISTRO_COMMENT="RHEL-compatible enterprise distro."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/rocky-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/rocky-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/rocky.sh"
}
