# Kali Linux, from the NetHunter rootfs images.
#
# Kali is the one distribution RedTerm has never built and the one upstream has no recipe
# for. It is not Termux's: the rootfs is NetHunter's own, published by Kali at
# kali.download/nethunter-images, and RedTerm has pointed at it since v2.1.0. This recipe
# moves that URL under our control so it is checksummed, trimmed and baked like the rest.
#
# Rolling, and there is no version to pin. NetHunter publishes only a `current/` path, so a
# pinned sha256 would break the install the next time Kali refreshes the image. That is the
# same reasoning as the first version of this recipe in RedTerm's registry, and it is why
# the image recorded here is verifiable rather than reproducible: the upstream sha256 is
# fetched and checked at build time, so what we publish is known-good, but a rebuild a week
# later is a different image.
#
# Arch: all four of RedTerm's. Verified 200 for arm64, armhf, amd64 and i386.

dist_name="Kali Linux"
dist_version="current"
distro_arches="aarch64 arm i686 x86_64"

KALI_BASE="https://kali.download/nethunter-images/current/rootfs"

kali_upstream_arch() {
	case "$1" in
		aarch64) echo "arm64";;
		arm)     echo "armhf";;
		i686)    echo "i386";;
		x86_64)  echo "amd64";;
		*) echo "kali_upstream_arch(): unknown arch '$1'" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch up_arch rootfs_dir tarball tgz

	for arch in ${distro_arches}; do
		up_arch=$(kali_upstream_arch "$arch")
		rootfs_dir="kali-${arch}"
		tgz="kali-nethunter-rootfs-minimal-${up_arch}.tar.xz"
		tarball="${ROOTFS_DIR}/kali-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		curl --fail --location --output "${WORKDIR}/${tgz}" "${KALI_BASE}/${tgz}"

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}"
		sudo mkdir -m 755 "${WORKDIR}/${rootfs_dir}"
		# The tarball has a single top-level directory named after the architecture
		# (kali-arm64/), so it is stripped.
		sudo tar -xJp --strip-components=1 -f "${WORKDIR}/${tgz}" -C "${WORKDIR}/${rootfs_dir}"

		sudo rm -f "${WORKDIR:?}/${rootfs_dir}/etc/resolv.conf"
		sudo tee "${WORKDIR}/${rootfs_dir}/etc/resolv.conf" > /dev/null <<< "nameserver 1.1.1.1"

		cat <<- EOF | sudo unshare -mpf bash -e -
			set -e
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" /bin/sh -e -c '
				export DEBIAN_FRONTEND=noninteractive
				apt-get update
				apt-get -y upgrade
				apt-get clean
				rm -rf /var/lib/apt/lists/* /var/log/apt/*
			'
		EOF

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Kali Linux"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" \
		"true"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "kali" "$arch" "${dist_version}" \
			"\"displayName\": \"Kali Linux\"" \
			"\"source\": \"${KALI_BASE}/${tgz}\"" \
			"\"packageManager\": \"apt\"" \
			"\"rolling\": true" \
			"\"verified\": false" \
			"\"recipe\": \"distro-build/kali.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
		unset tgz
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/kali.sh instead.
		DISTRO_NAME="Kali Linux"
		DISTRO_COMMENT="Penetration testing and security research. Rolling, so the checksum is verified at build time rather than pinned."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/kali-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/kali-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/kali.sh"
}
