# Void Linux, from the official live ROOTFS tarballs.
#
# Modelled on termux/proot-distro's distro-build/void.sh at commit 5bd8f4f.
#
# The one thing deliberately NOT carried over: upstream runs every xbps-install with
#
#     env SSL_NO_VERIFY_PEER=1
#
# which turns off certificate verification for the package manager. Every package in a
# Void image would then be accepted without proving who served it. Whatever motivated it
# -- almost certainly a missing or expired CA bundle in the minimal image -- is fixed
# here the way every other recipe fixes it, by installing ca-certificates first, so the
# fetch is verified rather than the check being switched off.
#
# The tarballs are Void's own live ROOTFS builds, which are real minimal images rather
# than an installer ISO.

# NOTE: deliberately no --acls/--xattrs on extraction. Those flags make GNU tar treat
# some tarballs as containing multiple concatenated archives and extract ZERO files,
# exiting with only "tar: Multiple archive files require '-M' option" -- a message that
# names nothing about the real cause. Confirmed on Gentoo stage3 (0 of 69373 members) and
# ARMtix (0 of 98731); plain extraction gets every one of them. Creating an archive still
# uses --acls/--xattrs in archive_rootfs, which is a different operation and works.
dist_name="Void Linux"
dist_version="20250202"
distro_arches="aarch64 arm i686 x86_64"

void_arch_for() {
	case "$1" in
		aarch64) echo "aarch64";;
		arm) echo "armv7l";;
		i686) echo "i686";;
		x86_64) echo "x86_64";;
		*) echo "void_arch_for(): unknown arch '$1'" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch up_arch rootfs_dir tarball

	for arch in ${distro_arches}; do
		up_arch=$(void_arch_for "$arch")
		rootfs_dir="void-${arch}"
		tarball="${ROOTFS_DIR}/void-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		curl --fail --location \
			--output "${WORKDIR}/void-${up_arch}-ROOTFS-${dist_version}.tar.xz" \
			"https://repo-default.voidlinux.org/live/${dist_version}/void-${up_arch}-ROOTFS-${dist_version}.tar.xz"

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}"
		sudo mkdir -m 755 "${WORKDIR}/${rootfs_dir}"
		sudo tar -Jxp \
			-f "${WORKDIR}/void-${up_arch}-ROOTFS-${dist_version}.tar.xz" \
			-C "${WORKDIR}/${rootfs_dir}"

		# ca-certificates first, with verification left on. Upstream's SSL_NO_VERIFY_PEER=1
		# was a workaround for precisely this being absent.
		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Void Linux"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" \
			"xbps-install -Suy ca-certificates && xbps-install -y xbps && xbps-install -y bash && xbps-reconfigure -fa"

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}/var/cache/xbps"/* 2>/dev/null || true

		# The root shell is set to bash so a session starts where the rest of the app expects.
		sudo unshare -mpf bash -e -c "
			set -e
			mount --bind /dev '${WORKDIR}/${rootfs_dir}/dev'
			mount --bind /proc '${WORKDIR}/${rootfs_dir}/proc'
			mount --bind /sys '${WORKDIR}/${rootfs_dir}/sys'
			chroot '${WORKDIR}/${rootfs_dir}' usermod --shell /bin/bash root
			chroot '${WORKDIR}/${rootfs_dir}' update-ca-certificates --fresh
		"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "void" "$arch" "${dist_version}" \
			"\"displayName\": \"Void\"" \
			"\"packageManager\": \"xbps\"" \
			"\"recipe\": \"distro-build/void.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
		unset up_arch
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/void.sh instead.
		DISTRO_NAME="Void Linux"
		DISTRO_COMMENT="Rolling release, fast package manager."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/void-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/void-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/void.sh"
}
