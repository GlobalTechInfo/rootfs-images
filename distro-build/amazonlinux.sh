# Amazon Linux 2023 (amzn2023), aarch64 and x86_64.
#
# Source is the official minimal image from Amazon's public ECR:
#
#   public.ecr.aws/amazonlinux/amazonlinux:2023.9.20251208.0-minimal
#
# AL2 (the "2.0" generation) ended standard support on 2026-06-30, so it is not
# what RedTerm ships. AL2023 is the supported generation: its image records
# SUPPORT_END=2029-06-30. The tag is a dated build, not the floating
# 2023-minimal alias, so a rebuild is a rebuild and not a moving target; the
# manifest digests the pull lands on are
#
#   aarch64  sha256:491fa52371a4d3853e641545fa03d8e190a029e55764bde7b1af046be5ca5673
#   x86_64   sha256:ff42e0ce16545f62ae7d75dd0fd4ce9015133a40cc4d9b13b50071e8e9ce74cc
#
# No repository rewrite: the image ships its own Amazon Linux 2023 repository
# (mirrorlist on cdn.amazonlinux.com, gpg key in /etc/pki), and that is
# exactly what stays. Treating it as fedora (its ID_LIKE line says fedora) is
# what once deleted those repositories and wrote dead mirrors.kernel.org
# Fedora URLs into the image; the amzn key in RedTerm injects nothing instead.
#
# AL2023 is dnf, and dnf has no -q: every quiet flag anywhere else in this
# project that meant yum's -q is not a dnf flag, and "dnf -q" is an error,
# measured. The chroot block therefore uses plain dnf.
#
# The minimal image also ships a dead usr/bin/gpgv2 -> gpgv link (neither
# gpgv nor a gpgv2 package exists in the image). It is not a working command,
# verify-rootfs refuses an image with a broken command link, and dnf does its
# signature work without it, so the link is removed as build hygiene.

dist_name="Amazon Linux"
dist_version="2023"

# RedTerm offers AL2023 on its two 64-bit architectures only; Amazon publishes
# no 32-bit minimal variant.
distro_arches="aarch64 x86_64"

# The OCI reference one pull serves both architectures; OCI_ARCH picks.
image_ref_for() {
	echo "public.ecr.aws/amazonlinux/amazonlinux:2023.9.20251208.0-minimal"
}

bootstrap_distribution() {
	local arch ref rootfs_dir tarball

	for arch in ${distro_arches}; do
		ref=$(image_ref_for "$arch")
		rootfs_dir="amazonlinux-${arch}"
		tarball="${ROOTFS_DIR}/amazonlinux-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" "$ref" "${WORKDIR}/${rootfs_dir}"

		# Runs under binfmt_misc + qemu-user when arch is not the host's; the
		# command is identical either way, which is the almalinux pattern. Plain
		# dnf: it has no -q, and a flag it does not know is a hard error here.
		cat <<- EOF | sudo unshare -mpf bash -e -
			rm -f "${WORKDIR}/${rootfs_dir}/etc/resolv.conf"
			echo "nameserver 1.1.1.1" > "${WORKDIR}/${rootfs_dir}/etc/resolv.conf"
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" /usr/bin/dnf -y install sudo passwd util-linux
			chroot "${WORKDIR}/${rootfs_dir}" /usr/bin/dnf clean all
			chroot "${WORKDIR}/${rootfs_dir}" rm -f /usr/bin/gpgv2
		EOF

		# The chroot ran as root, so the dnf state it created is root-owned and
		# the metadata caches are build-host noise. The rpm database itself is
		# part of the system and stays: it is what a session-side dnf upgrade
		# reasons about.
		sudo rm -rf "${WORKDIR}/${rootfs_dir}/var/lib/dnf" \
			"${WORKDIR}/${rootfs_dir}/var/cache/dnf" \
			"${WORKDIR}/${rootfs_dir}/var/log/dnf.log" \
			"${WORKDIR}/${rootfs_dir}/var/log/dnf.rpm.log"

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Amazon Linux"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "dnf -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "amazonlinux" "$arch" "$dist_version" \
			"\"displayName\": \"Amazon Linux\"" \
			"\"sourceImage\": \"${ref}\"" \
			"\"packageManager\": \"dnf\"" \
			"\"recipe\": \"distro-build/amazonlinux.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/amazonlinux.sh instead.
		DISTRO_NAME="Amazon Linux"
		DISTRO_COMMENT="Amazon's current RHEL-compatible Linux; dnf, supported through 2029."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/amazonlinux-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/amazonlinux-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/amazonlinux.sh"
}
