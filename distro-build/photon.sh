# Photon OS 4.0, aarch64 and x86_64.
#
# Source is docker.io/photon:4.0. Photon is a minimal container OS for cloud
# workloads; it ships tdnf (a C implementation of DNF without Python deps),
# not full dnf. tdnf in v4 has no -q flag, so plain commands are used.
#
# Arch: aarch64 and x86_64. The image publishes both; RedTerm ships these two.
#
# No SELinux: Photon does not include a selinux-policy package.
#
# No systemd or full init: this is a minimal container rootfs.

dist_name="Photon OS"
dist_version="4.0"
distro_arches="aarch64 x86_64"

image_ref_for() {
	case "$1" in
		aarch64) echo "docker.io/photon:4.0";;
		x86_64)  echo "docker.io/photon:4.0";;
		*) echo "Photon OS: no image for $1" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch ref rootfs_dir tarball

	for arch in ${distro_arches}; do
		ref=$(image_ref_for "$arch")
		rootfs_dir="photon-${arch}"
		tarball="${ROOTFS_DIR}/photon-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" "$ref" "${WORKDIR}/${rootfs_dir}"

		cat <<- EOF | sudo unshare -mpf bash -e -
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" tdnf -y update
			chroot "${WORKDIR}/${rootfs_dir}" tdnf -y install passwd util-linux sudo
			chroot "${WORKDIR}/${rootfs_dir}" tdnf clean all
		EOF

		# tdnf state directories are build-host noise; the rpm db is part of the
		# system and stays.
		sudo rm -rf "${WORKDIR}/${rootfs_dir}/var/cache/tdnf" \
			"${WORKDIR}/${rootfs_dir}/var/lib/tdnf" \
			"${WORKDIR}/${rootfs_dir}/var/log/tdnf.log" 2>/dev/null || true

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Photon OS"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "tdnf -y update"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "photon" "$arch" "$dist_version" \
			"\"displayName\": \"Photon OS\"" \
			"\"sourceImage\": \"$ref\"" \
			"\"packageManager\": \"tdnf\"" \
			"\"recipe\": \"distro-build/photon.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/photon.sh instead.
		DISTRO_NAME="Photon OS"
		DISTRO_COMMENT="Minimal cloud container OS; tdnf."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/photon-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/photon-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/photon.sh"
}
