# Red Hat UBI 10, aarch64 and x86_64.
#
# Source is docker.io/redhat/ubi10:latest — the full UBI 10 image, which ships
# dnf (not microdnf). The minimal variant (ubi10-minimal) ships microdnf with
# a reduced command set and no group/install-weak-deps control; the full UBI
# image is the better base for a proot session.
#
# Arch: aarch64 and x86_64. The image also publishes ppc64le and s390x;
# RedTerm ships the two common 64-bit architectures only.
#
# No SELinux: UBI does not include a selinux-policy package by default.

dist_name="Red Hat UBI"
dist_version="10"
distro_arches="aarch64 x86_64"

image_ref_for() {
	case "$1" in
		aarch64) echo "docker.io/redhat/ubi10:latest";;
		x86_64)  echo "docker.io/redhat/ubi10:latest";;
		*) echo "Red Hat UBI: no image for $1" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch ref rootfs_dir tarball

	for arch in ${distro_arches}; do
		ref=$(image_ref_for "$arch")
		rootfs_dir="redhat-${arch}"
		tarball="${ROOTFS_DIR}/redhat-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" "$ref" "${WORKDIR}/${rootfs_dir}"

		cat <<- EOF | sudo unshare -mpf bash -e -
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y upgrade
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y install passwd util-linux sudo
			chroot "${WORKDIR}/${rootfs_dir}" dnf clean all
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.log"
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.rpm.log"
		EOF

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Red Hat UBI"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "dnf -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "redhat" "$arch" "$dist_version" \
			"\"displayName\": \"Red Hat UBI\"" \
			"\"sourceImage\": \"$ref\"" \
			"\"packageManager\": \"dnf\"" \
			"\"recipe\": \"distro-build/redhat.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/redhat.sh instead.
		DISTRO_NAME="Red Hat UBI"
		DISTRO_COMMENT="Universal Base Image; RHEL-compatible, free."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/redhat-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/redhat-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/redhat.sh"
}
