# CentOS Stream 10, 10.
#
# Source is quay.io/centos/centos:stream10, built by osbuild. It ships
# dnf (not microdnf or tdnf), bash, and SELinux policy. The minimal variant
# (stream10-minimal) has no dnf binary, so the full image is used.
#
# Arch: aarch64 and x86_64. The upstream manifest list also carries ppc64le
# and s390x, but RedTerm ships the two 64-bit common architectures only.
#
# Container images have no machine-id and their SELinux policy is set for a
# container runtime. proot fakes root, not a security context, so SELinux
# stays installed and disabled-by-default, which is what proot needs.

dist_name="CentOS Stream"
dist_version="10"
distro_arches="aarch64 x86_64"

# RedTerm offers this on aarch64 and x86_64 only; the image does not exist
# for arm or i686.
image_ref_for() {
	case "$1" in
		aarch64) echo "quay.io/centos/centos:stream10";;
		x86_64)  echo "quay.io/centos/centos:stream10";;
		*) echo "CentOS Stream: no image for $1" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch ref rootfs_dir tarball

	for arch in ${distro_arches}; do
		ref=$(image_ref_for "$arch")
		rootfs_dir="centos-${arch}"
		tarball="${ROOTFS_DIR}/centos-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" "$ref" "${WORKDIR}/${rootfs_dir}"

		cat <<- EOF | sudo unshare -mpf bash -e -
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y upgrade
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y install passwd util-linux sudo
			chroot "${WORKDIR}/${rootfs_dir}" dnf clean all
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.log"
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.rpm.log"
		EOF

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "CentOS Stream"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "dnf -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "centos" "$arch" "$dist_version" \
			"\"displayName\": \"CentOS Stream\"" \
			"\"sourceImage\": \"$ref\"" \
			"\"packageManager\": \"dnf\"" \
			"\"recipe\": \"distro-build/centos.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/centos.sh instead.
		DISTRO_NAME="CentOS Stream"
		DISTRO_COMMENT="Upstream RHEL development preview; bug-for-bug RHEL."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/centos-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/centos-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/centos.sh"
}
