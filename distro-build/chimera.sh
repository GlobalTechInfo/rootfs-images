# Chimera Linux, a musl-based distribution.
#
# Modelled on termux/proot-distro's distro-build/chimera.sh at commit 5bd8f4f, which is
# the one upstream recipe that needed no redesign: Chimera publishes real bootstrap
# tarballs per architecture, so it is a download like Alpine rather than a container pull
# or a pacstrap build.
#
# Newer than upstream's pin. Upstream is on 20250420; 20251220 also exists and is what
# this builds.
#
# Arch: aarch64 and x86_64, which are the two RedTerm ships. Chimera also publishes
# riscv64, which upstream builds and RedTerm does not support.

dist_name="Chimera Linux"
dist_version="20251220"
distro_arches="aarch64 x86_64"

# Chimera publishes these names directly; aarch64 is already ours.
chimera_arch_for() {
	case "$1" in
		aarch64) echo "aarch64";;
		x86_64) echo "x86_64";;
		*) echo "chimera_arch_for(): unknown arch '$1'" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch up_arch rootfs_dir tarball

	for arch in ${distro_arches}; do
		up_arch=$(chimera_arch_for "$arch")
		rootfs_dir="chimera-${arch}"
		tarball="${ROOTFS_DIR}/chimera-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		curl --fail --location \
			--output "${WORKDIR}/chimera-linux-${up_arch}-ROOTFS-${dist_version}-bootstrap.tar.gz" \
			"https://repo.chimera-linux.org/live/${dist_version}/chimera-linux-${up_arch}-ROOTFS-${dist_version}-bootstrap.tar.gz"

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}"
		sudo mkdir -m 755 "${WORKDIR}/${rootfs_dir}"
		sudo tar -zxp \
			-f "${WORKDIR}/chimera-linux-${up_arch}-ROOTFS-${dist_version}-bootstrap.tar.gz" \
			-C "${WORKDIR}/${rootfs_dir}"

		sudo rm -f "${WORKDIR:?}/${rootfs_dir}/etc/resolv.conf"
		sudo tee "${WORKDIR}/${rootfs_dir}/etc/resolv.conf" > /dev/null <<< "nameserver 1.1.1.1"

		# Chimera is apk-based, so this is the same shape as Alpine's.
		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Chimera Linux"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" \
		"true" \
			"apk add --no-cache --no-interactive bash"

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}/var/cache/apk"/* 2>/dev/null || true
		sudo rm -f "${WORKDIR:?}/${rootfs_dir}/var/log/apk.log" 2>/dev/null || true

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "chimera" "$arch" "${dist_version}" \
			"\"displayName\": \"Chimera Linux\"" \
			"\"packageManager\": \"apk\"" \
			"\"rolling\": true" \
			"\"recipe\": \"distro-build/chimera.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
		unset up_arch
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/chimera.sh instead.
		DISTRO_NAME="Chimera Linux"
		DISTRO_COMMENT="musl-based, dhcbsd and BSD userland. ${dist_version}."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/chimera-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/chimera-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/chimera.sh"
}
