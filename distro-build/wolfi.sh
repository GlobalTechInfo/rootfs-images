# Wolfi, rolling, aarch64 and x86_64.
#
# Source is docker.io/chainguard/wolfi-base:latest. Wolfi is a Chainguard
# distro built on apk (not dnf). The base image ships busybox sh as the
# default shell with no bash, no coreutils, no shadow, no util-linux and
# no sudo — all must be installed during the build.
#
# Arch: aarch64 and x86_64. The image publishes both; RedTerm ships these two.
#
# No SELinux: Wolfi does not include a selinux-policy package.
# No systemd: this is a minimal container rootfs.
#
# wolfi is a rolling release: the version is whatever the :latest tag
# currently points at, not a fixed release number.

dist_name="Wolfi"
dist_version="latest"
distro_arches="aarch64 x86_64"

image_ref_for() {
	case "$1" in
		aarch64) echo "docker.io/chainguard/wolfi-base:latest";;
		x86_64)  echo "docker.io/chainguard/wolfi-base:latest";;
		*) echo "Wolfi: no image for $1" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch ref rootfs_dir tarball

	for arch in ${distro_arches}; do
		ref=$(image_ref_for "$arch")
		rootfs_dir="wolfi-${arch}"
		tarball="${ROOTFS_DIR}/wolfi-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" "$ref" "${WORKDIR}/${rootfs_dir}"

		cat <<- EOF | sudo unshare -mpf bash -e -
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" apk add --no-cache shadow util-linux sudo bash coreutils
			chroot "${WORKDIR}/${rootfs_dir}" apk upgrade --no-cache
		EOF

		# The apk download cache is build-host noise; it also changes on every
		# build and would break reproducibility.
		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}/var/cache/apk"/* 2>/dev/null || true
		sudo rm -f "${WORKDIR:?}/${rootfs_dir}/var/log/apk.log"

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Wolfi"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" \
			"apk upgrade --no-cache"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "wolfi" "$arch" "$dist_version" \
			"\"displayName\": \"Wolfi\"" \
			"\"sourceImage\": \"$ref\"" \
			"\"packageManager\": \"apk\"" \
			"\"rolling\": true" \
			"\"recipe\": \"distro-build/wolfi.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/wolfi.sh instead.
		DISTRO_NAME="Wolfi"
		DISTRO_COMMENT="Security-hardened rolling distro; Chainguard."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/wolfi-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/wolfi-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/wolfi.sh"
}
