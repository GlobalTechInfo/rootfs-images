# Slackware, from the aclemons/slackware registry image.
#
# Slackware publishes no rootfs tarball of any kind -- only slackware-15.0 DVD/CD ISOs --
# so there is nothing to download. The working source is a community container image,
# `aclemons/slackware:current`, which is also the reference proot-distro v5 lists among
# the images it recommends. Verified: the manifest list carries 386, amd64 and arm64.
#
# That matches RedTerm's three 64-bit-plus architectures exactly, and i386 too.
#
# A third-party image is a trust decision: aclemons is not Slackware. That is recorded in
# the index as sourceImage so it is visible rather than buried, and the sha256 we publish
# is of the tree we actually built.

dist_name="Slackware"
dist_version="current"
distro_arches="aarch64 i686 x86_64"

bootstrap_distribution() {
	local arch rootfs_dir tarball

	for arch in ${distro_arches}; do
		rootfs_dir="slackware-${arch}"
		tarball="${ROOTFS_DIR}/slackware-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" \
			"docker.io/aclemons/slackware:current" "${WORKDIR}/${rootfs_dir}"

		sudo rm -f "${WORKDIR:?}/${rootfs_dir}/etc/resolv.conf"
		sudo tee "${WORKDIR}/${rootfs_dir}/etc/resolv.conf" > /dev/null <<< "nameserver 1.1.1.1"

		# The image has no TLS stack at all: no /etc/ssl directory, no curl, no wget, no
		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Slackware"
		# openssl. So trim-rootfs.sh correctly refuses it -- every https call in a session
		# would fail -- and the fix is to install the CA bundle rather than to relax the
		# check. Slackware takes its certificates from the ca-certificates package, which
		# cannot be installed without working pkgtools, so the build host's Mozilla bundle
		# is copied in. That is a deliberate substitution, not a build artefact: it is the
		# same set of roots every other image here verifies against.
		sudo mkdir -p "${WORKDIR}/${rootfs_dir}/etc/ssl/certs"
		sudo cp /etc/ssl/certs/ca-certificates.crt \
			"${WORKDIR}/${rootfs_dir}/etc/ssl/certs/ca-certificates.crt"

		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "true"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "slackware" "$arch" "${dist_version}" \
			"\"displayName\": \"Slackware\"" \
			"\"sourceImage\": \"docker.io/aclemons/slackware:current\"" \
			"\"thirdPartyImage\": true" \
			"\"packageManager\": \"slackpkg\"" \
			"\"rolling\": true" \
			"\"recipe\": \"distro-build/slackware.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/slackware.sh instead.
		DISTRO_NAME="Slackware"
		DISTRO_COMMENT="Traditional, script-centric. Rolling current."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/slackware-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/slackware-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/slackware.sh"
}
