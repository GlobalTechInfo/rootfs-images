# Trisquel, from the official archive with mmdebstrap.
#
# Modelled on termux/proot-distro's distro-build/trisquel.sh at commit 5bd8f4f, whose
# approach is still correct: Trisquel is a pure Debian derivative with an ordinary apt
# archive, so this is the same shape as the Debian and Ubuntu recipes.
#
# All four of RedTerm's architectures, as upstream builds. Verified 200 for aramo,
# aramo-updates, aramo-security and aramo-backports.
#
# --variant=apt rather than minbase, as upstream has it: Trisquel's own base set is small
# and this matches what the distribution ships.

dist_name="Trisquel"
dist_version="aramo"
distro_arches="aarch64 arm i686 x86_64"

TRISQUEL_REPO="https://archive.trisquel.org/trisquel"

trisquel_deb_arch() {
	case "$1" in
		aarch64) echo "arm64";;
		arm)     echo "armhf";;
		i686)    echo "i386";;
		x86_64)  echo "amd64";;
		*) echo "trisquel_deb_arch(): unknown arch '$1'" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch deb_arch rootfs_dir tarball

	require_tools mmdebstrap

	for arch in ${distro_arches}; do
		deb_arch=$(trisquel_deb_arch "$arch")
		rootfs_dir="trisquel-${arch}"
		tarball="${ROOTFS_DIR}/trisquel-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		# The keyring, fetched from the archive, exactly as for Pardus.
		#
		# mmdebstrap cannot bootstrap without it: every Trisquel suite comes back
		# "InRelease is not signed" and it stops with a PIPE. Upstream does not pass
		# --keyring because it lists trisquel-keyring in --include, but an --include is
		# applied AFTER the base system is fetched, so it cannot help verify the base.
		if [ ! -f "${WORKDIR}/trisquel-archive-keyring.gpg" ]; then
			curl --fail --location \
				--output "${WORKDIR}/trisquel-archive-keyring.deb" \
				"${TRISQUEL_REPO}/pool/main/t/trisquel-keyring/trisquel-keyring_2023.02.07_all.deb"
			sudo dpkg-deb --fsys-tarfile "${WORKDIR}/trisquel-archive-keyring.deb" \
				| sudo tar -xO ./usr/share/keyrings/trisquel-archive-keyring.gpg \
				> "${WORKDIR}/trisquel-archive-keyring.gpg"
		fi

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}"

		sudo mmdebstrap \
			--architectures="${deb_arch}" \
			--variant=apt \
			--components="main" \
			--include="ca-certificates,locales,trisquel-keyring,software-properties-common,passwd,sudo" \
			--keyring="${WORKDIR}/trisquel-archive-keyring.gpg" \
			--format=directory \
			"${dist_version}" \
			"${WORKDIR}/${rootfs_dir}" \
			"deb ${TRISQUEL_REPO} ${dist_version} main" \
			"deb ${TRISQUEL_REPO} ${dist_version}-updates main" \
			"deb ${TRISQUEL_REPO} ${dist_version}-security main" \
			"deb ${TRISQUEL_REPO} ${dist_version}-backports main"

		# apt's lists and cache are a download cache: large, useless in a session, and
		# they change whenever the archive is touched.
		# mmdebstrap's --keyring does not survive into the image, so the first
		# apt-get update fails with "not signed" for every suite until it is copied in.
		sudo mkdir -p "${WORKDIR}/${rootfs_dir}/etc/apt/trusted.gpg.d"
		sudo cp "${WORKDIR}/trisquel-archive-keyring.gpg" \
			"${WORKDIR}/${rootfs_dir}/etc/apt/trusted.gpg.d/trisquel-archive-keyring.gpg"

		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}/var/lib/apt/lists"/* 2>/dev/null || true
		sudo rm -rf "${WORKDIR:?}/${rootfs_dir}/var/cache/apt/archives"/* 2>/dev/null || true
		sudo rm -f "${WORKDIR:?}/${rootfs_dir}/etc/resolv.conf"
		sudo tee "${WORKDIR}/${rootfs_dir}/etc/resolv.conf" > /dev/null <<< "nameserver 1.1.1.1"

		cat <<- EOF | sudo unshare -mpf bash -e -
			set -e
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" /bin/sh -e -c '
				apt-get update
				apt-get -y upgrade
				apt-get clean
				rm -rf /var/lib/apt/lists/* /var/log/apt/*
			'
		EOF

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Trisquel"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" \
			"apt-get update && apt-get -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "trisquel" "$arch" "${dist_version}" \
			"\"displayName\": \"Trisquel\"" \
			"\"source\": \"${TRISQUEL_REPO}\"" \
			"\"packageManager\": \"apt\"" \
			"\"recipe\": \"distro-build/trisquel.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
		unset deb_arch
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/trisquel.sh instead.
		DISTRO_NAME="Trisquel"
		DISTRO_COMMENT="Fully free GNU/Linux distribution based on Ubuntu. ${dist_version}."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/trisquel-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/trisquel-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/trisquel.sh"
}
