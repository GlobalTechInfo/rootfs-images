# Azure Linux 4, aarch64 and x86_64.
#
# Source is mcr.microsoft.com/azurelinux/core:4 — the GA 4.0 image. Azure Linux
# is RHEL-compatible (v4 is RHEL 10-compatible). The image ships dnf5 as
# /usr/bin/dnf; the dnf5 cache lives at var/cache/libdnf5, not var/cache/dnf.
#
# Arch: aarch64 and x86_64. The image publishes both; RedTerm ships these two.
#
# SELinux is included (libselinux + selinux-policy) but disabled-by-default in
# the container image, same as almalinux and rocky: proot fakes root, not a
# security context, so the policy is left installed but not enforcing.
#
# No systemd services: this is a minimal container rootfs.
#
# The 3.0 line (mcr.microsoft.com/azurelinux/base/core:3.0) uses tdnf and is
# EOL; 4.0 GA uses dnf5.

dist_name="Azure Linux"
dist_version="4"
distro_arches="aarch64 x86_64"

image_ref_for() {
	case "$1" in
		aarch64) echo "mcr.microsoft.com/azurelinux/core:4";;
		x86_64)  echo "mcr.microsoft.com/azurelinux/core:4";;
		*) echo "Azure Linux: no image for $1" >&2; exit 1;;
	esac
}

bootstrap_distribution() {
	local arch ref rootfs_dir tarball

	for arch in ${distro_arches}; do
		ref=$(image_ref_for "$arch")
		rootfs_dir="azurelinux-${arch}"
		tarball="${ROOTFS_DIR}/azurelinux-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" "$ref" "${WORKDIR}/${rootfs_dir}"

		cat <<- EOF | sudo unshare -mpf bash -e -
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y upgrade
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y install shadow-utils util-linux sudo
			chroot "${WORKDIR}/${rootfs_dir}" dnf clean all
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.log"
			rm -f "${WORKDIR}/${rootfs_dir}/var/log/dnf.rpm.log"
		EOF

		# dnf5 keeps its cache under var/cache/libdnf5, not var/cache/dnf.
		# The rpm db is part of the system and stays.
		sudo rm -rf "${WORKDIR}/${rootfs_dir}/var/cache/libdnf5" 2>/dev/null || true

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Azure Linux"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "dnf -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "azurelinux" "$arch" "$dist_version" \
			"\"displayName\": \"Azure Linux\"" \
			"\"sourceImage\": \"$ref\"" \
			"\"packageManager\": \"dnf5\"" \
			"\"recipe\": \"distro-build/azurelinux.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/azurelinux.sh instead.
		DISTRO_NAME="Azure Linux"
		DISTRO_COMMENT="RHEL-compatible; Microsoft Azure Linux."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/azurelinux-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/azurelinux-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/azurelinux.sh"
}
