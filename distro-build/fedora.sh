# Fedora, from the official Fedora Container Base image.
#
# Modelled on termux/proot-distro's distro-build/fedora.sh at commit 5bd8f4f, which reads a
# pre-packed `.oci.tar.xz` with jq. That still works and the whiteout walk is the same, but
# requiring every recipe to have a tarball published in a particular layout is a constraint
# the other RHEL-family distributions do not meet, so the shared oci-unpack.sh is used
# instead and this recipe carries only what is specific to Fedora.
#
# Arch: aarch64 and x86_64, matching the image RedTerm has always offered. The Fedora
# manifest list also carries 386, ppc64le and s390x, none of which RedTerm ships.
#
# SELinux is the Fedora-specific hazard. proot fakes root, not a security context, so an
# enforcing SELinux in the image blocks ordinary file operations. The container image ships
# with SELinux disabled by default, which is correct here; RedTerm's /root/.startup
# re-applies that on every start and opts authselect out, so nothing has to be done to the
# image beyond leaving it alone.

dist_name="Fedora"
dist_version="44"
distro_arches="aarch64 x86_64"

bootstrap_distribution() {
	local arch rootfs_dir tarball

	for arch in ${distro_arches}; do
		rootfs_dir="fedora-${arch}"
		tarball="${ROOTFS_DIR}/fedora-${arch}-rt-${CURRENT_VERSION}.tar.xz"

		OCI_ARCH="$arch" "${SCRIPT_DIR}/oci-unpack.sh" \
			"docker.io/library/fedora:${dist_version}" "${WORKDIR}/${rootfs_dir}"

		cat <<- EOF | sudo unshare -mpf bash -e -
			mount --bind /dev "${WORKDIR}/${rootfs_dir}/dev"
			mount --bind /proc "${WORKDIR}/${rootfs_dir}/proc"
			mount --bind /sys "${WORKDIR}/${rootfs_dir}/sys"
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y upgrade
			chroot "${WORKDIR}/${rootfs_dir}" dnf -y install passwd util-linux sudo
			chroot "${WORKDIR}/${rootfs_dir}" dnf clean all
			rm -f "${WORKDIR}/${rootfs_dir}"/var/log/dnf.log
			rm -f "${WORKDIR}/${rootfs_dir}"/var/log/dnf.rpm.log
		EOF

		"${SCRIPT_DIR}/verify-rootfs.sh" "${WORKDIR}/${rootfs_dir}" "Fedora"
		"${SCRIPT_DIR}/bake-first-start.sh" "${WORKDIR}/${rootfs_dir}" "dnf -y upgrade"

		"${SCRIPT_DIR}/trim-rootfs.sh" "${WORKDIR}/${rootfs_dir}"

		image_meta "$tarball" "fedora" "$arch" "${dist_version}" \
			"\"displayName\": \"Fedora\"" \
			"\"sourceImage\": \"docker.io/library/fedora:${dist_version}\"" \
			"\"packageManager\": \"dnf\"" \
			"\"recipe\": \"distro-build/fedora.sh\""

		archive_rootfs "$tarball" "$rootfs_dir"
		echo "[*] Built $tarball"
	done
	unset arch
}

write_plugin() {
	local arch tarball sha
	{
		cat <<- EOF
		# Generated by bootstrap-rootfs.sh. Do not edit: it is rewritten on every
		# build. Edit distro-build/fedora.sh instead.
		DISTRO_NAME="Fedora"
		DISTRO_COMMENT="Modern, innovative, upstream for RHEL."

		EOF
		for arch in ${distro_arches}; do
			tarball="${ROOTFS_DIR}/fedora-${arch}-rt-${CURRENT_VERSION}.tar.xz"
			if [ ! -f "$tarball" ]; then
				echo "[!] ${tarball} is missing, cannot write its sha256." >&2
				exit 1
			fi
			sha=$(sha256sum "$tarball" | awk '{ print $1}')
			echo "TARBALL_URL['${arch}']=\"${GIT_RELEASE_URL}/fedora-${arch}-rt-${CURRENT_VERSION}.tar.xz\""
			echo "TARBALL_SHA256['${arch}']=\"${sha}\""
		done
	} > "${PLUGIN_DIR}/fedora.sh"
}
